// Хлебные крошки на странице статьи блога: проверка, что статья не висит
// в поиске сама по себе.
//
// Каждая статья лежит внутри раздела «Кейсы», и поисковик понимает это
// либо по видимой строке крошек (`Главная / Кейсы / <заголовок>`), либо по
// разметке BreadcrumbList в JSON-LD. Без обоих сигналов он индексирует
// статью как самостоятельную страницу, иерархия раздела рассыпается, и
// вес с родительских страниц до статьи не доходит — это известная беда
// 11 октября 2026 у всех 15 статей.
//
// Функция чистая и HTML не читает с диска: её вызывает и проверка сборки,
// и тесты, у которых готовый HTML уже в руках. Отдельно две беды названы
// потому, что в диффе видно сразу — пропала видимая строка или разметка,
// и понятно, какую половину работы возвращать.

const SCHEMA_BREADCRUMB_SUBSTRING = '"@type":"BreadcrumbList"'

// Класс ищем по именам из списка, а не подстрокой. Подстрока с границей слова
// не годится: дефис эту границу даёт, поэтому класс разделителя
// `article-crumbs-sep` сходил за саму строку крошек, и страж молчал на
// странице, где строки уже нет. Найдено при ревью 18.10.2026 — попыткой
// доказать, что страж вообще срабатывает.
function hasVisibleCrumbs(html) {
  for (const match of html.matchAll(/class="([^"]*)"/g)) {
    if (match[1].trim().split(/\s+/).includes('article-crumbs')) return true
  }
  return false
}

/**
 * @param {{path: string, html: string}[]} pages только страницы статей
 * @returns {string[]} по строке на каждую найденную беду; пусто, если всё на месте
 */
export function gradeBreadcrumbs(pages) {
  const found = []
  for (const { path, html } of pages) {
    // Класс article-crumbs может идти среди других: `class="article-crumbs x"`
    // это та же строка крошек, и придираться к соседям страж не должен.
    if (!hasVisibleCrumbs(html)) {
      found.push(
        `${path}: нет видимой строки крошек (класс article-crumbs) — поисковик увидит статью без иерархии`,
      )
    }
    if (!html.includes(SCHEMA_BREADCRUMB_SUBSTRING)) {
      found.push(`${path}: нет разметки BreadcrumbList — поисковик не свяжет статью с разделом «Кейсы»`)
    }
  }
  return found
}
