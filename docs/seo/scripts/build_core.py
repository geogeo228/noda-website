"""Сборка семантического ядра из выгрузок bukvarix и *_suggest.

Модуль устроен так, что его можно импортировать без побочных эффектов:
всё чтение файлов и запись результата выполняются только при прямом
запуске скрипта. Правила кластеров и фильтр отсева мусора — предметные
решения заказчика, менять их нельзя: ни выражения, ни порядок, ни
состав.
"""

import collections
import glob
import re


# отсев мусора: нужен контекст бизнеса/ИИ/ботов/автоматизации
_BIZ_FILTER_RX = r'автоматиз|бот|\bии\b|нейросет|искусственн|транскриб|расшифр|распознав|crm|мини|mini|n8n|приложен|фотоотч|выкладк|фотозон|фотобудк|протокол|аудит|трекер'

# Оставлено на верхнем уровне модуля для совместимости с прежним кодом:
# переменная использовалась раньше и в неё могли смотреть извне.
BIZ = r'бизнес|компани|предприят|клиент|заяв|продаж|малого|b2b|отдел|менеджер|сотрудник|crm|телеграм|telegram|тг |мини|n8n|сайт'


def normalize_phrase(phrase):
    """Нормализовать фразу: пробелы в один, регистр в нижний, ё → е, обрезка."""
    return re.sub(r'\s+', ' ', phrase.strip().lower().replace('ё', 'е'))


# Правила кластеров: первый подошедший regex побеждает.
# Порядок и состав — предметное решение, менять нельзя.
RULES = [
    ('транскрибация и протоколы', r'транскриб|расшифров|протокол|аудио в текст|речь в текст|голос в текст|созвон|совещани'),
    ('документы и распознавание', r'документ|паспорт|распознаван|анкет|ocr|скан'),
    ('ритейл: выкладка и фотоотчёты', r'выкладк|мерчандайз|фотоотч|полк'),
    ('мероприятия и ивенты', r'мероприят|фестивал|свадьб|ивент|event|фотозон|фотобудк|конференц'),
    ('мини-аппы Telegram', r'мини ?-?апп|mini ?app|miniapp'),
    ('боты: разработка и заказ', r'(бот|бота|боты|ботов|чатбот).*(разработ|заказ|созда|под ключ|услуг|стоимост|цена|купить|сделать)|(разработ|заказ|созда|под ключ|услуг).*(бот|бота|боты|ботов)'),
    ('боты: общие', r'\bбот|чат-бот|чатбот|боты|ботов|ассистент|помощник|ии агент|ai agent'),
    ('автоматизация процессов и рутины', r'автоматизац|рутин|бизнес-?процесс|регламент|аудит'),
    ('ИИ и нейросети для бизнеса', r'\bии\b|нейросет|искусственн|\bai\b|gpt|внедрени'),
    ('веб-приложения, CRM, трекеры', r'crm|веб-?приложен|трекер|корпоративн|внутренн|приложени|портал|личный кабинет'),
    ('инструменты: n8n, make, no-code', r'n8n|make\.com|no-?code|zapier|low-?code|интеграц'),
    ('туризм/недвижимость/фарма/школа', r'туроператор|турагент|риелтор|риэлтор|брокер|недвижим|фарм|пациент|школ|онлайн-?школ|обучени'),
]


def classify(phrase):
    """Первый подошедший кластер по списку правил, или None."""
    for name, rx in RULES:
        if re.search(rx, phrase):
            return name
    return None


def passes_business_filter(phrase):
    """True, если во фразе есть хотя бы один признак бизнес-контекста."""
    return bool(re.search(_BIZ_FILTER_RX, phrase))


# маркеры интента: ищем по подстроке в уже нормализованной фразе, корень
# без окончания (напр. «услуг» поймает и «услуги», и «услуга»).
# Порядок проверки важен и зафиксирован заказчиком: сначала
# информационные (человек ещё хочет сам, продавать рано), потом
# коммерческие.
_INFORMATIONAL_MARKERS = (
    'как сделать', 'как создать', 'своими руками', 'самому', 'бесплатно',
    'что такое', 'что это', 'инструкция', 'пример', 'примеры', 'курс',
    'курсы', 'обучение', 'урок', 'уроки', 'python', 'скачать',
    'онлайн бесплатно',
)
_COMMERCIAL_MARKERS = (
    'цена', 'цены', 'стоимость', 'сколько стоит', 'заказать', 'на заказ',
    'купить', 'под ключ', 'услуг', 'разработка', 'разработать', 'компания',
    'агентство', 'студия', 'внедрение', 'внедрить', 'аутсорс', 'подрядчик',
)


def detect_intent(phrase):
    """Интент фразы: «информационный», «коммерческий» или «неясный».

    Правила проверяются в порядке: информационные → коммерческие →
    неясный. Первое подошедшее правило побеждает. Порядок зафиксирован
    заказчиком и менять его нельзя.
    """
    for marker in _INFORMATIONAL_MARKERS:
        if marker in phrase:
            return 'информационный'
    for marker in _COMMERCIAL_MARKERS:
        if marker in phrase:
            return 'коммерческий'
    return 'неясный'


# Далее — код прямого запуска скрипта. При импорте модуля этот блок не
# выполняется, поэтому `import build_core` не лезет в файловую систему
# и не требует наличия каталога `raw/` рядом.

if __name__ == '__main__':
    D = {}  # phrase -> dict

    def _add(p, src, fr=None):
        p = normalize_phrase(p)
        if not p or len(p) > 90:
            return
        d = D.setdefault(p, {'src': set(), 'fr': None})
        d['src'].add(src)
        if fr and (d['fr'] is None or int(fr.split('/')[0]) > int(d['fr'].split('/')[0])):
            d['fr'] = fr

    for f in ['raw/bukvarix.tsv', 'raw/bukvarix2.tsv', 'raw/bukvarix3.tsv']:
        for i, l in enumerate(open(f, encoding='utf-8')):
            if i == 0:
                continue
            p = l.rstrip('\n').split('\t')
            if len(p) < 4 or not p[2].isdigit() or not p[3].isdigit():
                continue
            _add(p[1], 'bukvarix', f'{p[2]}/{p[3]}')

    for f in glob.glob('raw/suggest_*.tsv') + ['raw/suggest.tsv']:
        for i, l in enumerate(open(f, encoding='utf-8')):
            if i == 0:
                continue
            p = l.rstrip('\n').split('\t')
            if len(p) < 3:
                continue
            _add(p[2], p[0] + '-suggest')

    rows = []
    for p, d in D.items():
        cl = classify(p)
        if cl is None:
            continue
        if not passes_business_filter(p):
            continue
        rows.append((p, d['fr'] or '', '+'.join(sorted(d['src'])), cl, detect_intent(p)))

    def _key(r):
        b = int(r[1].split('/')[0]) if r[1] else -1
        return (r[3], -b, r[0])

    rows.sort(key=_key)

    with open('2026-10-11-core.tsv', 'w', encoding='utf-8') as o:
        o.write('фраза\tчастотность_широкая/точная_весь_мир\tисточник\tкластер\tинтент\n')
        for r in rows:
            o.write('\t'.join(r) + '\n')

    c = collections.Counter(r[3] for r in rows)
    print(len(D), 'уникальных всего;', len(rows), 'в core')
    for k, v in c.most_common():
        print(v, k)
    print('с цифрами:', sum(1 for r in rows if r[1]),
          ' bukvarix:', sum('bukvarix' in r[2] for r in rows),
          ' yandex:', sum('yandex' in r[2] for r in rows),
          ' google:', sum('google' in r[2] for r in rows),
          ' bing:', sum('bing' in r[2] for r in rows))

